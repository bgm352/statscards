def load_candidates(filepath: str = "seed_inventory.json") -> List[ArbitrageCandidate]:
    if os.path.exists(filepath):
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                raw_list = json.load(f)
            return [ArbitrageCandidate(**item) for item in raw_list]
        except Exception:
            pass
    return [ArbitrageCandidate(**item) for item in DEFAULT_SEED_DATA]


